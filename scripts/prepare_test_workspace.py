def build_markdown_template(row: pd.Series, annotator_id: str) -> str:
    pid = str(row["page_id"])
    ch_id = str(row["chapter_id"])
    bk_pg = int(row["book_page"])
    tags = str(row["layout_tags"])
    ch_title = CHAPTER_TITLES.get(ch_id, f"অধ্যায়: {ch_id}")
    spec_note = PAGE_SPECIFIC_NOTES.get(pid, f"### {pid} মূল পাঠ্য")

    md = f"""# পেজ ট্রান্সক্রিপশন ও অ্যানোটেশন: {pid} (বইয়ের পৃষ্ঠা: {bk_pg})
- **অধ্যায়:** {ch_title}
- **স্প্লিট:** Held-Out Test Set (LOCKED — মানব ট্রান্সক্রিপশন ও অ্যানোটেশন ওয়ার্কস্পেস)
- **অ্যানোটেটর আইডি:** `{annotator_id}`
- **লেআউট ট্যাগ:** `{tags}`
- **স্ক্যান চিত্র:** `data/raw_scans/test/{pid}.png`
- **নির্দেশিকা:** মূল স্ক্যান থেকে হুবহু বানান, যুক্তাক্ষর, যতিচিহ্ন ও ফরম্যাটিং বজায় রেখে ট্রান্সক্রিপশন সম্পন্ন করুন।

---

{spec_note}

<!-- মূল স্ক্যানচিত্র দেখে নির্ভুল বাংলা পাঠ্য এখানে ট্রান্সক্রাইব করুন -->
[এখানে মূল পাঠ্য ট্রান্সক্রাইব করুন...]

---

## সত্তা ও সম্পর্ক অ্যানোটেশন চেকলিস্ট (Entity & Relation Annotations)

### ১. মূল ঐতিহাসিক সত্তাসমূহ (Named Entities):
<!-- Allowed: PERSON, ORGANIZATION, LOCATION, EVENT, DATE/PERIOD, DOCUMENT/TREATY/LAW -->
- [ ] `সত্তা_১` | টাইপ: [PERSON / DATE / LOC / ORG / EVENT / DOC] | char_offsets: [start, end]
- [ ] `সত্তা_২` | টাইপ: [PERSON / DATE / LOC / ORG / EVENT / DOC] | char_offsets: [start, end]

### ২. নির্দেশিত ঐতিহাসিক সম্পর্কসমূহ (Directed Relations):
<!-- Allowed: participated_in, led_by, member_of, occurred_at, occurred_on, caused, resulted_in, preceded, signed_issued, located_in -->
- [ ] (Subject) --[relation_type]--> (Object) | evidence_span: "..."

### ৩. ঐতিহাসিক ঘটনা ফ্রেম (Event Frames):
<!-- Multi-slot structure: trigger, event_type, date, location, participants, causes, consequences -->
- [ ] ইভেন্ট ট্রিগার: "..." | টাইপ: [...] | তারিখ: [...] | স্থান: [...]
"""
    return md


def main():
    root_dir = Path(__file__).resolve().parent.parent
    csv_p = root_dir / "data" / "pages.csv"
    df = pd.read_csv(csv_p)

    test_pages = df[(df["split"] == "test") & (df["page_type"] == "core_prose")].sort_values("page_id")
    print(f"Generating test annotation templates for {len(test_pages)} core prose pages...")

    for ann_name in ["annotator_1_test", "annotator_2_test"]:
        out_dir = root_dir / "data" / "gold_standard" / ann_name
        out_dir.mkdir(parents=True, exist_ok=True)
        count = 0
        for _, row in test_pages.iterrows():
            pid = row["page_id"]
            md_content = build_markdown_template(row, ann_name)
            md_path = out_dir / f"{pid}.md"
            with open(md_path, "w", encoding="utf-8") as f:
                f.write(md_content)
            count += 1
        print(f"Generated {count} templates under: data/gold_standard/{ann_name}/")


if __name__ == "__main__":
    main()
