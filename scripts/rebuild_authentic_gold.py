def ground_entity(gold_text: str, name: str, entity_type: str, entity_id: str) -> dict:
    idx = gold_text.find(name)
    if idx == -1:
        clean_name = " ".join(name.split())
        idx = gold_text.find(clean_name)
        if idx != -1:
            name = clean_name
    if idx == -1:
        raise ValueError(f"Entity '{name}' not found in gold_text of length {len(gold_text)}!")
    char_start = idx
    char_end = idx + len(name)
    assert gold_text[char_start:char_end] == name, f"Mismatch: '{gold_text[char_start:char_end]}' != '{name}'"
    return {
        "entity_id": entity_id,
        "name": name,
        "entity_type": entity_type,
        "char_start": char_start,
        "char_end": char_end,
        "evidence_span": name
    }


def find_clause(text: str, target: str) -> str:
    for s in text.replace("\n", " ").split("।"):
        if target in s:
            return s.strip() + "।"
    return target


